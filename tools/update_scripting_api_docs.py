def _exports(cls, excluded):
    members = [(name, func) for name, func in vars(cls).items()
               if getattr(func, '_APIExport', False) and name not in excluded]
    members.sort(key=lambda item: inspect.getsourcelines(item[1])[1])
    return members


def _public(cls):
    members = [(name, func) for name, func in vars(cls).items()
               if inspect.isfunction(func) and not name.startswith('_')]
    members.sort(key=lambda item: inspect.getsourcelines(item[1])[1])
    return members


def _signature(func):
    signature = inspect.signature(func)
    parameters = [p for p in signature.parameters.values() if p.name != 'self']
    return str(signature.replace(parameters=parameters,
                                 return_annotation=inspect.Signature.empty))


def _entry(prefix, name, func, owner):
    doc = (inspect.getdoc(func) or '').strip()
    if doc:
        # Google-style sections (Args:, Returns:) as napoleon renders them
        # for autodoc; a plain docstring passes through unchanged.
        from sphinx.ext.napoleon import Config
        from sphinx.ext.napoleon.docstring import GoogleDocstring
        doc = str(GoogleDocstring(doc, Config(napoleon_use_param=True,
                                              napoleon_use_rtype=True))).strip()
    if not doc:
        raise SystemExit(f'{owner}.{name} is exported to the scripting API '
                         'without a docstring; write one.')
    lines = [f'.. py:function:: {prefix}{name}{_signature(func)}', '   :no-index:', '']
    lines += ['   ' + line.rstrip() if line.strip() else '' for line in doc.splitlines()]
    return '\n'.join(lines) + '\n\n'


def render():
    out = [HEADER]
    for title, widget, intro, classes in GROUPS:
        out.append(f'{title}\n{"-" * len(title)}\n\n')
        out.append(f'*Widget:* ``{widget}``. {intro}\n\n')
        for module, clsname, excluded in classes:
            cls = getattr(importlib.import_module(module), clsname)
            for name, func in _exports(cls, excluded):
                out.append(_entry('api.imcontrol.', name, func, clsname))
    from imswitch.imcontrol.controller.CommunicationChannel import CommunicationChannel
    out.append(SIGNALS_INTRO)
    signalsDoc = inspect.getdoc(CommunicationChannel.signals)
    out.append(signalsDoc[signalsDoc.index(' - '):signalsDoc.index('They can be')]
               .replace('\n ', '\n').strip() + '\n\n')
    from imswitch.imscripting.model.actions import _Actions
    out.append(HELPERS_INTRO)
    for name, func in _public(_Actions):
        out.append(_entry('', name, func, '_Actions'))
    return ''.join(out).rstrip('\n') + '\n'


def main():
    os.environ.setdefault('QT_QPA_PLATFORM', 'offscreen')
    sys.path.insert(0, str(REPO))
    text = render()
    if '--check' in sys.argv:
        current = OUTPUT.read_text(encoding='utf-8') if OUTPUT.exists() else ''
        if current != text:
            raise SystemExit(f'{OUTPUT.relative_to(REPO)} is stale; run '
                             'python tools/update_scripting_api_docs.py')
        print(f'{OUTPUT.relative_to(REPO)} is current')
        return
    OUTPUT.write_text(text, encoding='utf-8')
    print(f'{OUTPUT.relative_to(REPO)}: {text.count(".. py:function::")} functions')


if __name__ == '__main__':
    main()
