HEADER = '''\
.. Generated by tools/update_scripting_api_docs.py from the controllers'
   @APIExport methods -- do not edit by hand; edit the docstrings and run
   the tool.

.. _scripting-api:

Scripting API reference
=======================

Everything a script can call, by the widget that provides it: a function
exists only while its widget is loaded (``availableWidgets`` in the setup
file, see :doc:`imcontrol-setups`), and ``api.imcontrol`` raises
``AttributeError`` for the others. Every function returns its value, or
raises its exception, in the script; the ones that drive the GUI run on
the GUI thread and block the script until they have run (see
:doc:`scripting` for the threading model, waiting for signals and the
tutorials). Names of devices are the ones the setup file gives them --
``getDetectorNames()``, ``getLaserNames()``, ``getPositionerNames()`` and
``getRotatorNames()`` list them.

'''

